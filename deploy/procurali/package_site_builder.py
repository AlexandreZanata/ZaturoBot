#!/usr/bin/env python3
"""Packages the Procurali Next.js storefront as a self-contained VPS site builder.

CI runs this after `npm ci` in the prototype directory. The result is copied into the release
bundle under `site-builder/` and is consumed by `procurali_site_sync.py`, which invokes
`runtime/node src/build.mjs --api-snapshot <file> --out-dir <dir>` on every catalog change.

The output must survive the deploy agent's safe extraction, so it contains only regular files
and directories: `node_modules/.bin` symlinks are dropped (the builder calls Next.js through
`node_modules/next/dist/bin/next`) and any remaining link or special file is an error.
Platform packages that a glibc x64 VPS never loads (musl/wasm builds, sharp for image
optimization, which the static export disables) are pruned to keep the bundle small.
"""

from __future__ import annotations

import argparse
import os
import shutil
import stat
import sys
from pathlib import Path

# Generated by scripts/prepare.mjs or next build; never shipped.
GENERATED_TOP_LEVEL = {".generated", ".next", "out", "public", "test", "next-env.d.ts"}
GENERATED_PREFIXES = ("out-", ".next-")
PRUNED_NODE_MODULES = (
    ".bin",
    "@img",
    "sharp",
    "@next/swc-linux-x64-musl",
    "lightningcss-linux-x64-musl",
    "@tailwindcss/oxide-linux-x64-musl",
    "@tailwindcss/oxide-wasm32-wasi",
)
REQUIRED_PATHS = (
    "src/build.mjs",
    "scripts/prepare.mjs",
    "package.json",
    "package-lock.json",
    "next.config.mjs",
    "node_modules/next/dist/bin/next",
)


def is_generated(name: str) -> bool:
    return name in GENERATED_TOP_LEVEL or name.startswith(GENERATED_PREFIXES)


def copy_package(source: Path, dest: Path) -> None:
    if dest.exists():
        raise FileExistsError(f"destination already exists: {dest}")
    dest.mkdir(parents=True)
    for entry in sorted(source.iterdir()):
        if is_generated(entry.name):
            continue
        target = dest / entry.name
        if entry.is_symlink():
            continue
        if entry.is_dir():
            shutil.copytree(entry, target, symlinks=True)
        elif entry.is_file():
            shutil.copy2(entry, target)


def prune_node_modules(package_dir: Path) -> list[str]:
    removed: list[str] = []
    node_modules = package_dir / "node_modules"
    for rel in PRUNED_NODE_MODULES:
        target = node_modules / rel
        if target.is_symlink() or target.is_file():
            target.unlink()
        elif target.is_dir():
            shutil.rmtree(target)
        else:
            continue
        removed.append(rel)
    return removed


def assert_regular_tree(root: Path) -> None:
    """Fails on anything the deploy agent's safe tar extraction would reject."""
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        for name in dirnames + filenames:
            path = Path(dirpath) / name
            mode = path.lstat().st_mode
            if not (stat.S_ISDIR(mode) or stat.S_ISREG(mode)):
                raise ValueError(f"unsupported member type in site builder: {path.relative_to(root)}")


def install_node_runtime(package_dir: Path, node_binary: Path) -> Path:
    resolved = node_binary.resolve(strict=True)
    if not resolved.is_file():
        raise FileNotFoundError(f"node runtime is not a regular file: {node_binary}")
    runtime = package_dir / "runtime" / "node"
    runtime.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(resolved, runtime)
    os.chmod(runtime, 0o755)
    return runtime


def package_site_builder(source: Path, dest: Path, node_binary: Path | None) -> list[str]:
    for rel in REQUIRED_PATHS:
        if not (source / rel).is_file():
            raise FileNotFoundError(f"missing {rel} in {source}; run `npm ci` first")
    copy_package(source, dest)
    removed = prune_node_modules(dest)
    if node_binary is not None:
        install_node_runtime(dest, node_binary)
    assert_regular_tree(dest)
    return removed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, required=True, help="prototype directory after npm ci")
    parser.add_argument("--dest", type=Path, required=True, help="new site-builder directory")
    parser.add_argument("--node", type=Path, help="node executable to bundle as runtime/node")
    args = parser.parse_args(argv)
    removed = package_site_builder(args.source.resolve(), args.dest, args.node)
    print(f"Packaged Procurali site builder into {args.dest} (pruned: {', '.join(removed) or 'none'}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
